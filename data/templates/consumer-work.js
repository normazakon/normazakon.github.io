  /** Процент из строки: «7,5» и «7.5 %» → 7.5. */
  function parsePercent(value) {
    const match = /^(\d+(?:[.,]\d+)?)\s*%?$/.exec(String(value || "").trim());
    return match ? Number(match[1].replace(",", ".")) : null;
  }

