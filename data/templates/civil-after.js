  function indexation(values, helpers) {
    const sum = helpers.parseMoney(values.amount);
    const percent = Number(String(values.index || "").replace(",", ".").replace("%", "").trim());
    if (sum === null || !Number.isFinite(percent) || percent <= 0) return null;
    return Math.round((sum * (percent - 100)) / 100);
  }

