    const base = helpers.parseMoney(values.base);
    const rate = Number(String(values.rate || "").replace(",", ".").replace("%", "").trim());
    const days = penaltyDays(values, helpers);
    if (base === null || !Number.isFinite(rate) || rate <= 0 || days === null || days < 0) return null;
