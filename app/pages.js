/* Служебные страницы: условия использования, конфиденциальность, контакты и «страница не найдена». */
(function () {
  "use strict";

  const { h } = window.UI;

  function site() {
    return window.SITE || {};
  }

  function dateText(iso) {
    const [year, month, day] = iso.split("-");
    return `${day}.${month}.${year}`;
  }

  function contactLine() {
    const { email } = site();
    return email
      ? h("a", { href: `mailto:${email}` }, email)
      : h("span", { class: "legal-missing" }, "адрес для связи будет указан на странице «Контакты»");
  }

  /** Страница с заголовком, датой редакции и разделами [заголовок, ...абзацы]. */
  function legalPage(root, title, updated, lead, sections) {
    root.append(h("article", { class: "legal" },
      h("div", { class: "page-head" }, h("div", {},
        h("h1", {}, title),
        updated ? h("p", {}, `Редакция от ${dateText(updated)}`) : null)),
      lead ? h("p", { class: "legal-lead" }, lead) : null,
      sections.map(([heading, ...paragraphs]) => h("section", {},
        h("h2", {}, heading),
        paragraphs.map((paragraph) => (Array.isArray(paragraph)
          ? h("ul", {}, paragraph.map((item) => h("li", {}, item)))
          : h("p", {}, paragraph)))))));
  }

  window.Views = window.Views || {};

  window.Views.terms = function (root) {
    legalPage(root, "Условия использования", site().termsUpdated,
      "«Норма» — бесплатная демонстрационная версия сервиса для работы с документами и нормами права. Открывая сайт, вы соглашаетесь с этими условиями.",
      [
        ["Что это за сервис",
          "Сервис помогает собрать документ из шаблона, проверить ссылки на статьи законов, найти статью и выполнить типовые расчёты. Это справочный инструмент, а не юридическая помощь и не консультация. Он не заменяет работу юриста и не учитывает обстоятельства вашего дела."],
        ["Шаблоны документов",
          "Шаблоны являются черновиками: их сверяли с текстом законов, но практикующий юрист ещё не проверял. Перед подписанием или подачей документа проверьте его текст, реквизиты и применимые нормы самостоятельно или с юристом.",
          "Документы, которые вы собрали, принадлежат вам, их можно свободно использовать, изменять и передавать."],
        ["База законов и расчёты",
          "Тексты статей и их прежние редакции взяты с Официального интернет-портала правовой информации (pravo.gov.ru) на дату сборки базы. Изменения, внесённые после сборки, в базе появятся только при следующем обновлении. Официальные редакции на портале есть с июля 2022 года, более ранние тексты сервис не показывает.",
          "Расчёты пошлины, процентов и неустойки выполняются по формулам из закона и по ключевой ставке Банка России. Результат может отличаться от расчёта суда, например из-за моратория, уменьшения неустойки или особых правил для отдельных категорий дел."],
        ["Ваши данные",
          "Всё, что вы вводите, хранится только в вашем браузере. Мы не получаем ваши документы и не можем их восстановить. Если очистить данные браузера или открыть сайт на другом устройстве, черновиков там не будет, поэтому сохраняйте важные документы в Word. Подробнее на странице «Конфиденциальность»."],
        ["Ответственность",
          "Сервис предоставляется бесплатно в том виде, в каком он есть. Мы стараемся, чтобы он работал без ошибок, но не гарантируем, что он подойдёт для вашей задачи и будет доступен без перерывов. Решение использовать документ или расчёт принимаете вы, в пределах, допускаемых законом, мы не отвечаем за последствия такого решения.",
          "Сервис может меняться, в том числе могут появиться платные функции. О платных функциях будет сказано заранее, и они будут работать по отдельным условиям."],
        ["Изменение условий и связь",
          "Действующая редакция условий всегда опубликована на этой странице, дата редакции указана вверху.",
          h("span", {}, "Вопросы и замечания: ", contactLine(), ".")],
      ]);
  };

  window.Views.privacy = function (root) {
    legalPage(root, "Конфиденциальность", site().privacyUpdated,
      "Коротко: сервис не собирает ваши данные. Регистрации нет, формы ничего никуда не отправляют, документы остаются в вашем браузере.",
      [
        ["Что хранится на вашем устройстве",
          [
            "Черновики документов и введённые в них сведения хранятся в памяти браузера (localStorage) на этом устройстве и никуда не передаются.",
            "Файл, который вы загружаете в раздел «Проверка», читается прямо в браузере и не отправляется на сервер.",
            "Чтобы сайт открывался без интернета, браузер сохраняет копию его файлов и тексты законов. Ваших данных в этой копии нет.",
          ],
          "Удалить черновики можно в разделе «Документы». Чтобы удалить всё сразу, очистите данные этого сайта в настройках браузера."],
        ["Чего на сайте нет",
          ["Регистрации и учётных записей.", "Файлов cookie.", "Счётчиков посещений, аналитики и рекламы.", "Шрифтов и скриптов, загружаемых с чужих серверов."]],
        ["Хостинг",
          `Сайт размещён на ${site().hosting}. Как и любой сервер, хостинг при открытии страницы получает технические сведения: IP-адрес, тип браузера, запрошенный адрес. Владелец сайта к этим сведениям доступа не имеет и не использует их.`],
        ["Персональные данные ваших клиентов",
          "Если вы вводите в шаблон сведения о других людях, например о клиенте или контрагенте, они тоже остаются в вашем браузере. Мы их не получаем и не обрабатываем. Обязанности оператора персональных данных перед этими людьми в этом случае лежат на вас. Для пробы сервиса удобнее использовать вымышленные данные, их подставляет кнопка «Заполнить примером»."],
        ["Если это изменится",
          "Когда появятся учётные записи, синхронизация или оплата, мы опубликуем политику обработки персональных данных по закону № 152-ФЗ и будем запрашивать согласие отдельно, до того как вы что-либо отправите.",
          h("span", {}, "Вопросы о данных: ", contactLine(), ".")],
      ]);
  };

  window.Views.contacts = function (root) {
    const { owner, email } = site();
    const rows = owner ? [
      ["Владелец сайта", owner.name],
      owner.status ? ["Статус", owner.status] : null,
      owner.inn ? ["ИНН", owner.inn] : null,
      owner.address ? ["Адрес", owner.address] : null,
    ].filter(Boolean) : [];
    root.append(h("article", { class: "legal" },
      h("div", { class: "page-head" }, h("div", {}, h("h1", {}, "Контакты"))),
      rows.length ? h("dl", { class: "legal-details" }, rows.map(([term, value]) => [h("dt", {}, term), h("dd", {}, value)])) : null,
      h("p", {}, "Вопросы, замечания к шаблонам и сообщения об ошибках: ", contactLine(), "."),
      h("p", { class: "legal-note" }, "Юридические консультации по почте мы не даём.")));
  };

  window.Views.notFound = function (root) {
    root.append(h("div", { class: "not-found" },
      h("p", { class: "not-found-code" }, "404"),
      h("h1", {}, "Такой страницы нет"),
      h("p", {}, "Возможно, ссылка устарела или в адресе опечатка."),
      h("div", { class: "not-found-actions" },
        h("a", { class: "button primary", href: "#home" }, "На главную"),
        h("a", { class: "button", href: "#templates" }, "К шаблонам"))));
  };
})();
